using UnityEngine;

namespace Project.Maps
{
    /// <summary>
    /// Static data describing one map/scene for the World Map window: its
    /// stable id, display name, and its node's position in the window.
    /// Mirrors <see cref="Project.Skills.SkillDefinition"/>'s definition
    /// asset pattern — one asset per map, listed by a <see cref="MapDatabase"/>.
    /// </summary>
    [CreateAssetMenu(fileName = "MapDefinition", menuName = "Project/Maps/Map")]
    public class MapDefinition : ScriptableObject
    {
        [Tooltip("Must exactly match the Unity scene name this map represents.")]
        [SerializeField] private string mapId;

        [SerializeField] private string displayName;

        [Tooltip("Anchored position (pixels) of this map's node in the World Map window's content area. Top-left anchor: X grows right, Y grows downward as a negative value, matching WindowLayoutManager's convention.")]
        [SerializeField] private Vector2 mapPosition;

        [Tooltip("Top-down picture shown on this map's node in the World Map window and on the minimap. Left empty, the node shows a flat color. Generated by Tools > Maps > Capture Thumbnails.")]
        [SerializeField] private Sprite thumbnail;

        [Tooltip("World X and Z of the center of the area the thumbnail shows. Filled in by Tools > Maps > Capture Thumbnails.")]
        [SerializeField] private Vector2 thumbnailCenter;

        [Tooltip("Side length in meters of the square world area the thumbnail shows. Filled in by Tools > Maps > Capture Thumbnails.")]
        [SerializeField] private float thumbnailSideLength;

        /// <summary>Gets the id this map is looked up by — must match the Unity scene name.</summary>
        public string MapId => mapId;

        /// <summary>Gets the name shown to the player.</summary>
        public string DisplayName => displayName;

        /// <summary>Gets this map's node position in the World Map window.</summary>
        public Vector2 MapPosition => mapPosition;

        /// <summary>Gets the picture shown on this map's World Map node, or null when none was captured yet.</summary>
        public Sprite Thumbnail => thumbnail;

        /// <summary>Gets the world X (x) and Z (y) of the center of the area <see cref="Thumbnail"/> shows.</summary>
        public Vector2 ThumbnailCenter => thumbnailCenter;

        /// <summary>Gets the side length in meters of the square world area <see cref="Thumbnail"/> shows, or 0 when not captured yet.</summary>
        public float ThumbnailSideLength => thumbnailSideLength;
    }
}
