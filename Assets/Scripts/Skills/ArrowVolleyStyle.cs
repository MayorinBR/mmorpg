namespace Project.Skills
{
    /// <summary>
    /// How the arrows of an ammo skill are drawn when it is cast.
    /// </summary>
    public enum ArrowVolleyStyle
    {
        /// <summary>A single arrow flies to the target.</summary>
        Single,

        /// <summary>Two arrows leave the bow together and fly side by side.</summary>
        Parallel,

        /// <summary>Several arrows fall from above onto the target.</summary>
        Rain
    }
}
